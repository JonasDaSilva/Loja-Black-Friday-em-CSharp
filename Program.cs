🛒 Projeto de estudo em C#: simulando uma loja na Black Friday

Com a Black Friday chegando, criei um projeto em C# para praticar Programação Orientada a Objetos. Ele simula uma loja de produtos novos e seminovos, com compras de estoque, vendas e uma campanha de desconto.

✅ O que ele faz:
• Cadastra produtos novos e seminovos, cada tipo com seus valores fixos de desconto e garantia
• Registra compras de estoque e vendas, validando o estoque antes de vender
• Ativa a campanha de Black Friday e muda o preço de todos os produtos de uma vez
• Gera um relatório com faturamento, custo e lucro

📚 O que pratiquei: abstração, encapsulamento, herança, polimorfismo e interfaces.

⚠️ Os produtos e valores são fictícios. É só um projeto de estudo, sem ligação com os sistemas ou preços reais da empresa.

